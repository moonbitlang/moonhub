const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async function attachmentSmoke({ page, cli, query, base, root, temp, browser, context, git, blob, tree, github, initial }) {
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64');
  const bodyFile = path.join(temp, 'image-body.md');
  fs.writeFileSync(bodyFile, '![pixel](data:image/png;base64,' + png.toString('base64') + ')');
  const imageIssue = cli(['issue', 'create', '--title', 'Screenshot report', '--body-file', bodyFile]);
  assert.ok(imageIssue.description.includes('/root/demo/attachments/'));
  assert.ok(!imageIssue.description.includes('base64'));
  cli(['issue', 'comment', imageIssue.number, '--body-file', bodyFile]);
  const imageTree = tree(['040000 tree ' + github + '\t.github', '100644 blob ' + blob('image fixture\n') + '\tREADME.md']);
  git(['update-ref', 'refs/heads/image-review', git(['commit-tree', imageTree, '-p', initial, '-m', 'Image fixture'])]);
  const mr = cli(['mr', 'create', '--title', 'Review screenshots', '--source', 'image-review', '--target', 'main', '--body-file', bodyFile]);
  assert.ok(mr.description.includes('/root/demo/attachments/'));
  cli(['mr', 'edit', mr.number, '--edit-version', mr.edit_version, '--body-file', bodyFile]);
  assert.ok(cli(['mr', 'view', mr.number]).mr.description.includes('/root/demo/attachments/'));
  cli(['mr', 'comment', mr.number, '--version', mr.version, '--body-file', bodyFile]);
  const thread = cli(['mr', 'discussions', mr.number]).items[0].id;
  const commentImageUrl = cli(['mr', 'discussions', mr.number, '--discussion', thread]).discussion.root.body.match(/\]\(([^)]+)\)/)[1];
  cli(['mr', 'reply', mr.number, '--discussion', thread, '--body-file', bodyFile]);
  const inline = cli(['mr', 'inline-comment', mr.number, '--version', mr.version, '--path', 'README.md', '--side', 'new', '--start-line', '1', '--body-file', bodyFile]);
  assert.ok(inline.discussion.root.body.includes('/root/demo/attachments/'));
  const count = query('SELECT COUNT(*) AS count FROM attachment')[0].count;
  const largeFile = path.join(temp, 'large-image-body.md');
  const large = Buffer.concat([png, Buffer.alloc(96 * 1024)]);
  fs.writeFileSync(largeFile, '![larger](data:image/png;base64,' + large.toString('base64') + ')');
  const largeIssue = cli(['issue', 'create', '--title', 'Large inline screenshot', '--body-file', largeFile]);
  assert.ok(largeIssue.description.includes('/root/demo/attachments/'));
  assert.equal(query('SELECT COUNT(*) AS count FROM attachment')[0].count, count + 1);
  const imageUrl = imageIssue.description.match(/\]\(([^)]+)\)/)[1];
  const privateImage = await context.request.get(base + imageUrl);
  assert.equal(privateImage.status(), 200);
  assert.deepEqual(await privateImage.body(), png);
  const outsider = await browser.newContext();
  assert.notEqual((await outsider.request.get(base + imageUrl, { maxRedirects: 0 })).status(), 200);
  await outsider.close();
  cli(['mr', 'delete-comment', mr.number, '--comment', thread, '--version', mr.version]);
  assert.equal((await context.request.get(base + commentImageUrl)).status(), 200);
  cli(['mr', 'restore-comment', mr.number, '--comment', thread, '--version', mr.version]);
  assert.ok(cli(['mr', 'discussions', mr.number, '--discussion', thread]).discussion.root.body.includes(commentImageUrl));

  await page.goto(base + '/root/demo/issues/new');
  const field = page.locator('textarea[name=description]');
  const editor = page.locator('.markdown-editor').first();
  assert.equal(await editor.count(), 1);
  await page.locator('input[name=title]').fill('Investigate screenshot upload');
  const screenshot = await page.screenshot({ clip: { x: 260, y: 80, width: 720, height: 180 } });
  await field.fill('Screenshot from the report:\n\n');
  await editor.locator('input[type=file]').setInputFiles({ name: 'report.png', mimeType: 'image/png', buffer: screenshot });
  await page.waitForFunction(() => document.querySelector('textarea[name=description]').value.includes('/attachments/'));
  await editor.getByRole('button', { name: 'Preview', exact: true }).click();
  await editor.locator('.markdown-editor-preview img').waitFor();
  await page.waitForFunction(() => { const img = document.querySelector('.markdown-editor-preview img'); return img?.complete && img.naturalWidth > 0; });
  const review = path.join(root, '.impeccable/review/attachments');
  fs.mkdirSync(review, { recursive: true });
  await page.screenshot({ path: path.join(review, 'desktop-preview.png'), fullPage: true });
  await editor.getByRole('button', { name: 'Write', exact: true }).click();
  let requests = 0;
  await page.route('**/root/demo/attachments?*', async route => {
    if (++requests === 1) await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Temporary upload failure. Retry.' } }) });
    else await route.continue();
  });
  const original = await field.inputValue();
  await editor.locator('input[type=file]').setInputFiles({ name: 'retry.png', mimeType: 'image/png', buffer: png });
  await editor.getByRole('button', { name: 'Retry upload', exact: true }).waitFor();
  assert.ok((await editor.locator('[role=status]').textContent()).includes('Temporary upload failure. Retry.'));
  assert.equal(await field.inputValue(), original);
  await editor.getByRole('button', { name: 'Retry upload', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('textarea[name=description]').value.includes('retry.png'));
  await page.unroute('**/root/demo/attachments?*');
  await editor.locator('input[type=file]').setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
  await page.waitForFunction(() => document.querySelector('.markdown-editor-status').textContent.includes('Choose a PNG'));
  assert.equal(await editor.getByRole('button', { name: 'Retry upload', exact: true }).isVisible(), false);
  await page.route('**/root/demo/attachments?*', async route => {
    await new Promise(resolve => setTimeout(resolve, 300)); await route.continue();
  });
  await field.evaluate((element, bytes) => {
    const transfer = new DataTransfer(); transfer.items.add(new File([new Uint8Array(bytes)], 'pasted.png', { type: 'image/png' }));
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: transfer, bubbles: true, cancelable: true }));
  }, [...png]);
  await editor.getByRole('button', { name: 'Preview', exact: true }).click();
  assert.equal(await field.isVisible(), true);
  assert.ok((await editor.locator('[role=status]').textContent()).includes('Wait for image uploads'));
  await page.waitForFunction(() => document.querySelector('textarea[name=description]').value.includes('pasted.png'));
  await page.unroute('**/root/demo/attachments?*');
  await field.evaluate((element, bytes) => {
    const transfer = new DataTransfer(); transfer.items.add(new File([new Uint8Array(bytes)], 'dropped.png', { type: 'image/png' }));
    element.dispatchEvent(new DragEvent('drop', { dataTransfer: transfer, bubbles: true, cancelable: true }));
  }, [...png]);
  await page.waitForFunction(() => document.querySelector('textarea[name=description]').value.includes('dropped.png'));
  await page.screenshot({ path: path.join(review, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('#app-sidebar').getBoundingClientRect().right <= 1);
  assert.ok(await editor.getByRole('button', { name: 'Preview', exact: true }).evaluate(element => element.getBoundingClientRect().height >= 44));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(review, 'mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Create issue', exact: true }).click();
  await page.waitForURL(/\/issues\/\d+$/);
  assert.equal(await page.locator('.discussion-description img').count(), 4);
  await page.reload();
  assert.equal(await page.locator('.discussion-description img').count(), 4);
  await page.setViewportSize({ width: 1440, height: 1000 });
  fs.writeFileSync(path.join(review, 'receipt.json'), JSON.stringify({ status: 'passed', cli: ['issue description/comment', 'MR description/comment/reply/line anchor', 'inline body beyond 64 KiB'], browser: ['file upload', 'failure and retry preserve text', 'clipboard paste', 'file drop', 'server preview', 'mobile submission', 'reload persistence', 'private image access'] }, null, 2));
};
