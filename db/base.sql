BEGIN;

CREATE EXTENSION pgcrypto;

CREATE TYPE user_status AS ENUM ('active', 'disabled');
CREATE TYPE team_kind AS ENUM ('personal', 'org');
CREATE TYPE team_member_role AS ENUM ('owner', 'admin', 'member');
CREATE TYPE invitation_kind AS ENUM ('root', 'team_member');
CREATE TYPE invitation_status AS ENUM ('sent', 'accepted', 'revoked', 'expired');
CREATE TYPE email_outbox_status AS ENUM ('pending', 'sent', 'failed');
CREATE TYPE repository_visibility AS ENUM ('public', 'private');

COMMENT ON TYPE user_status IS 'Lifecycle state for an application account.';
COMMENT ON TYPE team_kind IS 'Team shape: personal teams model individual user namespaces, org teams model shared namespaces.';
COMMENT ON TYPE team_member_role IS 'Authorization role for a user within a team.';
COMMENT ON TYPE invitation_kind IS 'Account activation invitation purpose.';
COMMENT ON TYPE invitation_status IS 'Lifecycle state for an account activation invitation.';
COMMENT ON TYPE email_outbox_status IS 'Delivery state for an outbox email.';
COMMENT ON TYPE repository_visibility IS 'Repository visibility policy.';

CREATE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION set_updated_at() IS 'Maintains updated_at before row updates.';

CREATE TABLE "user" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_key text NOT NULL UNIQUE,
  display_name text NOT NULL,
  email text UNIQUE,
  password_hash text NOT NULL,
  is_site_admin boolean NOT NULL DEFAULT false,
  status user_status NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (name_key ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  CHECK (name_key <> 'assets'),
  CHECK (display_name <> ''),
  CHECK (email IS NULL OR (email = lower(email) AND email <> '')),
  CHECK (password_hash <> '')
);

COMMENT ON TABLE "user" IS 'Application account. A personal workspace is represented by a personal team, not by repository ownership on the user.';
COMMENT ON COLUMN "user".id IS 'Stable internal user identifier.';
COMMENT ON COLUMN "user".name_key IS 'URL-safe unique user key used in paths and lookups.';
COMMENT ON COLUMN "user".display_name IS 'Human-readable user display name.';
COMMENT ON COLUMN "user".email IS 'Optional login and notification email. Stored lowercase when present.';
COMMENT ON COLUMN "user".password_hash IS 'Password verifier produced by the application password hashing policy.';
COMMENT ON COLUMN "user".is_site_admin IS 'Whether the user can perform instance-wide administration such as creating organization teams.';
COMMENT ON COLUMN "user".status IS 'Current account lifecycle state.';
COMMENT ON COLUMN "user".created_at IS 'Time when the user record was created.';
COMMENT ON COLUMN "user".updated_at IS 'Time when the user record was last updated.';

CREATE TRIGGER set_user_updated_at
BEFORE UPDATE ON "user"
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TRIGGER set_user_updated_at ON "user" IS 'Refreshes updated_at before user updates.';

CREATE TABLE session (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  last_seen_at timestamptz,
  CHECK (token_hash <> ''),
  CHECK (expires_at > created_at),
  CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

COMMENT ON TABLE session IS 'Login session backed by an opaque application token stored as a hash.';
COMMENT ON COLUMN session.id IS 'Stable internal session identifier.';
COMMENT ON COLUMN session.user_id IS 'User that owns the session.';
COMMENT ON COLUMN session.token_hash IS 'Hash of the bearer token; the raw token is never stored.';
COMMENT ON COLUMN session.created_at IS 'Time when the session was created.';
COMMENT ON COLUMN session.expires_at IS 'Time when the session stops being valid.';
COMMENT ON COLUMN session.revoked_at IS 'Time when the session was manually revoked, if any.';
COMMENT ON COLUMN session.last_seen_at IS 'Last time this session was observed by the application.';

CREATE INDEX session_user_id_index
  ON session (user_id);

CREATE INDEX session_expires_at_index
  ON session (expires_at);

CREATE TABLE invitation_session (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invitation_id bigint NOT NULL,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CHECK (token_hash <> ''),
  CHECK (expires_at > created_at),
  CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

COMMENT ON TABLE invitation_session IS 'Short-lived session proving an invitation one-time password was accepted.';
COMMENT ON COLUMN invitation_session.id IS 'Stable internal invitation session identifier.';
COMMENT ON COLUMN invitation_session.invitation_id IS 'Invitation being activated.';
COMMENT ON COLUMN invitation_session.token_hash IS 'Hash of the invitation session token; the raw token is never stored.';
COMMENT ON COLUMN invitation_session.created_at IS 'Time when the invitation session was created.';
COMMENT ON COLUMN invitation_session.expires_at IS 'Time when the invitation session stops being valid.';
COMMENT ON COLUMN invitation_session.revoked_at IS 'Time when the invitation session was manually revoked, if any.';

CREATE INDEX invitation_session_invitation_id_index
  ON invitation_session (invitation_id);

CREATE TABLE team (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_key text NOT NULL UNIQUE,
  display_name text NOT NULL,
  kind team_kind NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (name_key ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  CHECK (name_key <> 'assets'),
  CHECK (display_name <> '')
);

COMMENT ON TABLE team IS 'Repository namespace and permission boundary. Repositories belong to teams, including personal teams.';
COMMENT ON COLUMN team.id IS 'Stable internal team identifier.';
COMMENT ON COLUMN team.name_key IS 'URL-safe unique team key used in paths and lookups.';
COMMENT ON COLUMN team.display_name IS 'Human-readable team display name.';
COMMENT ON COLUMN team.kind IS 'Whether this team represents a personal namespace or an organization namespace.';
COMMENT ON COLUMN team.created_at IS 'Time when the team record was created.';
COMMENT ON COLUMN team.updated_at IS 'Time when the team record was last updated.';

CREATE TRIGGER set_team_updated_at
BEFORE UPDATE ON team
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TRIGGER set_team_updated_at ON team IS 'Refreshes updated_at before team updates.';

CREATE TABLE team_member (
  team_id bigint NOT NULL REFERENCES team(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  role team_member_role NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (team_id, user_id)
);

COMMENT ON TABLE team_member IS 'Membership and role assignment for users in teams.';
COMMENT ON COLUMN team_member.team_id IS 'Team that grants the membership.';
COMMENT ON COLUMN team_member.user_id IS 'User that receives the membership.';
COMMENT ON COLUMN team_member.role IS 'Permission role held by the user in the team.';
COMMENT ON COLUMN team_member.created_at IS 'Time when the membership was created.';

CREATE INDEX team_member_user_id_index
  ON team_member (user_id);

CREATE TABLE invitation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind invitation_kind NOT NULL,
  email text NOT NULL,
  name_key text NOT NULL,
  display_name text NOT NULL,
  password_hash text NOT NULL,
  is_site_admin boolean NOT NULL DEFAULT false,
  team_id bigint REFERENCES team(id) ON DELETE CASCADE,
  team_role team_member_role,
  invited_by_user_id bigint REFERENCES "user"(id) ON DELETE RESTRICT,
  accepted_user_id bigint REFERENCES "user"(id) ON DELETE SET NULL,
  status invitation_status NOT NULL DEFAULT 'sent',
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '7 days'),
  accepted_at timestamptz,
  revoked_at timestamptz,
  CHECK (email = lower(email) AND email <> ''),
  CHECK (name_key ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  CHECK (name_key <> 'assets'),
  CHECK (display_name <> ''),
  CHECK (password_hash <> ''),
  CONSTRAINT invitation_kind_policy_check CHECK (
    (kind = 'root' AND is_site_admin AND team_id IS NULL AND team_role IS NULL AND invited_by_user_id IS NULL)
    OR
    (kind = 'team_member' AND NOT is_site_admin AND team_id IS NOT NULL AND team_role IN ('admin', 'member') AND invited_by_user_id IS NOT NULL)
  ),
  CHECK (expires_at > created_at),
  CHECK (accepted_at IS NULL OR accepted_at >= created_at),
  CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

COMMENT ON TABLE invitation IS 'Account activation invitation using a one-time password.';
COMMENT ON COLUMN invitation.id IS 'Stable internal invitation identifier.';
COMMENT ON COLUMN invitation.kind IS 'Purpose of the invitation.';
COMMENT ON COLUMN invitation.email IS 'Lowercase email address receiving the invitation.';
COMMENT ON COLUMN invitation.name_key IS 'Requested account name_key.';
COMMENT ON COLUMN invitation.display_name IS 'Display name used when creating the accepted user.';
COMMENT ON COLUMN invitation.password_hash IS 'Hash of the invitation one-time password.';
COMMENT ON COLUMN invitation.is_site_admin IS 'Whether accepting the invitation creates a site administrator.';
COMMENT ON COLUMN invitation.team_id IS 'Team granted by a team_member invitation.';
COMMENT ON COLUMN invitation.team_role IS 'Team role granted by a team_member invitation.';
COMMENT ON COLUMN invitation.invited_by_user_id IS 'User who created the invitation.';
COMMENT ON COLUMN invitation.accepted_user_id IS 'User created or attached when the invitation was accepted.';
COMMENT ON COLUMN invitation.status IS 'Current invitation lifecycle state.';
COMMENT ON COLUMN invitation.created_at IS 'Time when the invitation was created.';
COMMENT ON COLUMN invitation.expires_at IS 'Time after which the invitation is no longer usable.';
COMMENT ON COLUMN invitation.accepted_at IS 'Time when the invitation was accepted.';
COMMENT ON COLUMN invitation.revoked_at IS 'Time when the invitation was revoked.';

CREATE INDEX invitation_team_id_index
  ON invitation (team_id);

CREATE INDEX invitation_email_index
  ON invitation (email);

CREATE INDEX invitation_accepted_user_id_index
  ON invitation (accepted_user_id);

CREATE UNIQUE INDEX invitation_sent_name_key_index
  ON invitation (name_key)
  WHERE status = 'sent';

CREATE UNIQUE INDEX invitation_sent_email_index
  ON invitation (email)
  WHERE status = 'sent';

CREATE TABLE email_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invitation_id bigint REFERENCES invitation(id) ON DELETE SET NULL,
  to_email text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  template text NOT NULL DEFAULT 'plain',
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status email_outbox_status NOT NULL DEFAULT 'pending',
  attempt_count integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  locked_at timestamptz,
  locked_by text,
  last_error text,
  provider_message_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  CHECK (to_email = lower(to_email) AND to_email <> ''),
  CHECK (subject <> ''),
  CHECK (body <> ''),
  CHECK (template <> ''),
  CHECK (attempt_count >= 0),
  CHECK (locked_by IS NULL OR locked_by <> ''),
  CHECK (last_error IS NULL OR last_error <> ''),
  CHECK (provider_message_id IS NULL OR provider_message_id <> ''),
  CHECK (sent_at IS NULL OR sent_at >= created_at)
);

COMMENT ON TABLE email_outbox IS 'Transactional email messages queued by application workflows.';
COMMENT ON COLUMN email_outbox.id IS 'Stable internal email message identifier.';
COMMENT ON COLUMN email_outbox.invitation_id IS 'Invitation that queued this email, when the message belongs to an invitation workflow.';
COMMENT ON COLUMN email_outbox.to_email IS 'Lowercase recipient email address.';
COMMENT ON COLUMN email_outbox.subject IS 'Email subject.';
COMMENT ON COLUMN email_outbox.body IS 'Plain text email body.';
COMMENT ON COLUMN email_outbox.template IS 'Template identifier used to render this message.';
COMMENT ON COLUMN email_outbox.payload IS 'Structured template data captured for audit and future rendering.';
COMMENT ON COLUMN email_outbox.status IS 'Current delivery state.';
COMMENT ON COLUMN email_outbox.attempt_count IS 'Number of delivery attempts.';
COMMENT ON COLUMN email_outbox.next_attempt_at IS 'Earliest time the worker may retry delivery.';
COMMENT ON COLUMN email_outbox.locked_at IS 'Time when a worker claimed this message, if currently locked.';
COMMENT ON COLUMN email_outbox.locked_by IS 'Worker identifier that claimed this message, if currently locked.';
COMMENT ON COLUMN email_outbox.last_error IS 'Most recent delivery failure message.';
COMMENT ON COLUMN email_outbox.provider_message_id IS 'Provider-specific message identifier after successful delivery.';
COMMENT ON COLUMN email_outbox.created_at IS 'Time when the message was queued.';
COMMENT ON COLUMN email_outbox.sent_at IS 'Time when an external sender delivered the message, if known.';

CREATE INDEX email_outbox_to_email_index
  ON email_outbox (to_email);

CREATE INDEX email_outbox_invitation_id_index
  ON email_outbox (invitation_id);

CREATE INDEX email_outbox_sent_at_index
  ON email_outbox (sent_at);

CREATE INDEX email_outbox_pending_index
  ON email_outbox (next_attempt_at, id)
  WHERE status = 'pending';

ALTER TABLE invitation_session
  ADD CONSTRAINT invitation_session_invitation_id_fkey
  FOREIGN KEY (invitation_id) REFERENCES invitation(id) ON DELETE CASCADE;

CREATE TABLE repository (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES team(id) ON DELETE CASCADE,
  name text NOT NULL,
  display_name text,
  visibility repository_visibility NOT NULL DEFAULT 'private',
  git_path text,
  default_branch text NOT NULL DEFAULT 'HEAD',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (team_id, name),
  CHECK (name ~ '^[A-Za-z0-9._-]+$'),
  CHECK (name NOT IN ('.', '..')),
  CHECK (display_name IS NULL OR display_name <> ''),
  CHECK (git_path IS NULL OR git_path <> ''),
  CHECK (default_branch <> '')
);

COMMENT ON TABLE repository IS 'Git repository owned by a team namespace.';
COMMENT ON COLUMN repository.id IS 'Stable internal repository identifier.';
COMMENT ON COLUMN repository.team_id IS 'Team that owns the repository.';
COMMENT ON COLUMN repository.name IS 'Repository name within the owning team namespace.';
COMMENT ON COLUMN repository.display_name IS 'Optional human-readable repository display name.';
COMMENT ON COLUMN repository.visibility IS 'Repository visibility policy.';
COMMENT ON COLUMN repository.git_path IS 'Optional storage path for the repository on disk or in backing storage.';
COMMENT ON COLUMN repository.default_branch IS 'Default branch or symbolic ref used when no branch is specified.';
COMMENT ON COLUMN repository.created_at IS 'Time when the repository record was created.';
COMMENT ON COLUMN repository.updated_at IS 'Time when the repository record was last updated.';

CREATE INDEX repository_team_id_index
  ON repository (team_id);

CREATE INDEX repository_visibility_index
  ON repository (visibility);

CREATE TRIGGER set_repository_updated_at
BEFORE UPDATE ON repository
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMENT ON TRIGGER set_repository_updated_at ON repository IS 'Refreshes updated_at before repository updates.';

COMMIT;
